# Bài tập 1: List operations

# Khởi tạo danh sách
numbers = [10, 20, 30, 40, 50]

# Thêm phần tử vào cuối
numbers.append(60)

# Chèn phần tử ở vị trí 1
numbers.insert(1, 15)

# Xóa phần tử cuối
numbers.pop()

# Sắp xếp danh sách
numbers.sort()

print("Danh sách sau khi xử lý:", numbers)
print("Số phần tử:", len(numbers))
print("Phần tử đầu tiên:", numbers[0])
print("Phần tử cuối cùng:", numbers[-1])
